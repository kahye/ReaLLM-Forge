def build_phonological_assimilation_200() -> List[Dict[str, Any]]:
    items = []
    phrasings = [
        "음운 변동 규칙 ({rule}): '{word}'의 올바른 표준 발음은?",
        "표준 발음법 ({rule} 현상)에 따른 '{word}'의 정확한 발음 기호는?",
        "한국어 음운 규칙 ({rule})을 적용할 때 '{word}'의 올바른 발음은?",
        "다음 단어 '{word}'에서 일어나는 {rule} 현상의 결과로 올바른 발음은?",
    ]
    for i in range(200):
        rule, word, corr, dists = ASSIMILATION_POOL[i % len(ASSIMILATION_POOL)]
        phr = phrasings[(i // len(ASSIMILATION_POOL)) % len(phrasings)]
        if i >= len(ASSIMILATION_POOL):
            phr = f"{phr} [문항 {i+1}]"
        ctx = phr.format(rule=rule, word=word)
        cands = [f" {corr}"] + [f" {d}" for d in dists]
        items.append({
            "ctx": ctx,
            "candidates": cands,
            "answer": 0,
        })
    return items


