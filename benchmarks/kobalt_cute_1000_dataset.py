        items.append({
            "ctx": f"자모 연산: '{word}'의 두 글자에서 받침(종성)을 모두 제거하면? [문항 #{i+121}]",
            "candidates": [f" {ans_word}", f" {d1}", f" {d2}", f" {d3}"],
            "answer": 0,
        })

