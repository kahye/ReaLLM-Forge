def decompose_syl(ch: str) -> Tuple[int, int, int]:
    code = ord(ch) - 0xAC00
    l = code // 588
    v = (code % 588) // 28
    t = code % 28
    return l, v, t


def compose_syl(l: int, v: int, t: int) -> str:
    return chr(0xAC00 + l * 588 + v * 28 + t)


def get_choseong_str(word: str) -> str:
    res = []
    for c in word:
        if 0xAC00 <= ord(c) <= 0xD7A3:
            l, _, _ = decompose_syl(c)
            res.append(CHOSEONG_LIST[l])
        else:
            res.append(c)
    return "".join(res)


