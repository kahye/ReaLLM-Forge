    for i in range(40):
        word = rev_words[i % len(rev_words)]
        ans_word = word[1] + word[0]
        d1 = word[0] + word[1]
        d2 = word[0] + word[0]
        d3 = word[1] + word[1]
        items.append({
            "ctx": f"자모 연산: '{word}'의 두 글자 순서를 거꾸로 뒤집으면? [문항 #{i+161}]",
            "candidates": [f" {ans_word}", f" {d1}", f" {d2}", f" {d3}"],
            "answer": 0,
        })

    return items


