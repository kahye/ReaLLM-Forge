def build_vowel_harmony_200() -> List[Dict[str, Any]]:
    items = []
    for i in range(200):
        pos_w, neg_w, dists = VOWEL_HARMONY_PAIRS[i % len(VOWEL_HARMONY_PAIRS)]
        mode = (i // len(VOWEL_HARMONY_PAIRS)) % 4
        if mode == 0:
            # Bright -> Dark
            ctx = f"모음조화 비례식: 양성모음 의태어 '{pos_w}'에 대응하는 음성모음(어둡고 큰 느낌) 의태어는? [문항 {i+1}]"
            ans_w = neg_w
            cands = [f" {ans_w}"] + [f" {d}" for d in dists]
        elif mode == 1:
            # Dark -> Bright
            ctx = f"모음조화 비례식: 음성모음 의태어 '{neg_w}'에 대응하는 양성모음(밝고 작은 느낌) 의태어는? [문항 {i+1}]"
            ans_w = pos_w
            cands = [f" {ans_w}"] + [f" {d}" for d in dists]
        elif mode == 2:
            # Analogy format A:B = C:?
            ref_pos, ref_neg, _ = VOWEL_HARMONY_PAIRS[(i + 1) % len(VOWEL_HARMONY_PAIRS)]
            ctx = f"모음조화 비례식: '{ref_pos}'이 '{ref_neg}'이 될 때, '{pos_w}'에 대응하는 음성모음 의태어는? [문항 {i+1}]"
            ans_w = neg_w
            cands = [f" {ans_w}"] + [f" {d}" for d in dists]
        else:
            ref_pos, ref_neg, _ = VOWEL_HARMONY_PAIRS[(i + 1) % len(VOWEL_HARMONY_PAIRS)]
            ctx = f"모음조화 비례식: '{ref_neg}'이 '{ref_pos}'이 될 때, '{neg_w}'에 대응하는 양성모음 의태어는? [문항 {i+1}]"
            ans_w = pos_w
            cands = [f" {ans_w}"] + [f" {d}" for d in dists]

        items.append({
            "ctx": ctx,
            "candidates": cands,
            "answer": 0,
        })
    return items


