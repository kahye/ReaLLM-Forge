    for i in range(40):
        word = closed_words[i % len(closed_words)]
        l0, v0, t0 = decompose_syl(word[0])
        l1, v1, t1 = decompose_syl(word[1])
        ans_word = compose_syl(l0, v0, 0) + compose_syl(l1, v1, 0)
        d1 = compose_syl(l0, v0, t0) + compose_syl(l1, v1, 0)
